function Glass({ dew }: { dew: boolean }) {
  const drops = [pt(160, 140), pt(180, 170), pt(150, 190), pt(200, 130), pt(210, 175), pt(170, 205), pt(195, 200)];
  return (
    <Stage w={440} h={260} label="ঠান্ডা গ্লাসের বাইরে জলীয় বাষ্প জমছে">
      <path d="M150 90H250L238 220H162Z" fill="none" strokeWidth={3} strokeLinejoin="round" style={{ stroke: col.f }} />
      <path d="M156 130H244L238 220H162Z" strokeWidth={0} style={{ fill: col.t, opacity: 0.25 }} />
      {dew ? drops.map((d, i) => <Dot key={i} p={pt(d.x - 6 + (i % 2) * 12, d.y)} c="t" r={4} />) : null}
      {[310, 340, 370].map((x) => (
        <Dot key={x} p={pt(x, 100 + (x % 3) * 20)} c="m" r={3} />
      ))}
      <Lab p={pt(340, 160)} c="m">বাতাসে জলীয় বাষ্প</Lab>
    </Stage>
  );
}

function RHBar({ T }: { T: number }) {
  const ps = table.find(([t]) => t === T)?.[1] ?? 1.71;
  const rh = Math.min(100, (P / ps) * 100);
  return (
    <Stage w={440} h={260} label="আপেক্ষিক আর্দ্রতার দণ্ড">
      <rect x={60} y={90} width={320} height={34} rx={8} fill="none" strokeWidth={3} style={{ stroke: col.f }} />
      <rect x={60} y={90} width={(320 * rh) / 100} height={34} rx={8} style={{ fill: rh >= 100 ? col.r : col.p }} />
      <Seg a={pt(380, 80)} b={pt(380, 134)} dash c="m" w={2} />
      <Lab p={pt(380, 70)} c="m">100%</Lab>
      <Lab p={pt(220, 170)} c="f">{`${T}°C এ আপেক্ষিক আর্দ্রতা ${rh.toFixed(0)}%`}</Lab>
      <Lab p={pt(220, 200)} c="m">{`p = ${P} kPa, p_s = ${ps} kPa`}</Lab>
      {rh >= 100 ? <Lab p={pt(220, 232)} c="r">সম্পৃক্ত, শিশির জমছে</Lab> : null}
    </Stage>
  );
}

