const R = 0.0821;
const A = 3.64;
const B = 0.0427;

const zOf = (T: number, P: number) => 1 + (B - A / (R * T)) * (P / (R * T));

function ZGraph({ T }: { T: number }) {
  const O = pt(60, 220);
  const kx = 1.8;
  const yOf = (z: number) => O.y - ((Math.min(1.2, Math.max(0.4, z)) - 0.4) / 0.8) * 170;
  const d = Array.from({ length: 21 }, (_, i) => {
    const P = i * 10;
    return `${i === 0 ? "M" : "L"}${(O.x + P * kx).toFixed(1)} ${yOf(zOf(T, P)).toFixed(1)}`;
  }).join("");
  return (
    <Stage w={440} h={260} label="Z বনাম P গ্রাফ">
      <Vec a={O} b={pt(430, O.y)} c="m" w={2} />
      <Vec a={O} b={pt(O.x, 36)} c="m" w={2} />
      <Lab p={pt(414, 242)} c="m" anchor="end">P (atm)</Lab>
      <Lab p={pt(72, 40)} c="m" anchor="start">Z = PV ÷ nRT</Lab>
      <Seg a={pt(O.x, yOf(1))} b={pt(O.x + 360, yOf(1))} dash c="m" w={2} />
      <Lab p={pt(O.x + 364, yOf(1) - 8)} c="m" anchor="end">আদর্শ, Z = 1</Lab>
      <path d={d} fill="none" strokeWidth={4} strokeLinecap="round" style={{ stroke: col.r }} />
      <Lab p={pt(O.x + 6, O.y + 18)} c="m" anchor="start">0</Lab>
    </Stage>
  );
}

